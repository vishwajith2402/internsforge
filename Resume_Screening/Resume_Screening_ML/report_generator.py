# ============================================================
# SAFE FILE NAME
# ============================================================

def safe_filename(name):

    name = str(name)

    name = re.sub(
        r'[<>:"/\\|?*]',
        '',
        name
    )

    name = re.sub(
        r'\s+',
        '_',
        name
    )

    if not name:
        name = "candidate"

    return name[:80]


# ============================================================
# FORMAT PERCENTAGE
# ============================================================

def format_percentage(value):

    try:
        return f"{float(value):.1f}%"
    except:
        return "0.0%"


# ============================================================
# SCORE COLOR
# ============================================================

def score_color(score):

    try:
        score = float(score)
    except:
        score = 0

    if score >= 80:
        return GREEN

    if score >= 60:
        return ORANGE

    return RED


# ============================================================
# PAGE HEADER / FOOTER
# ============================================================

def draw_page(canvas, document):

    canvas.saveState()

    width, height = A4

    # --------------------------------------------
    # TOP LINE
    # --------------------------------------------

    canvas.setStrokeColor(
        PURPLE
    )

    canvas.setLineWidth(
        2
    )

    canvas.line(
        18 * mm,
        height - 15 * mm,
        width - 18 * mm,
        height - 15 * mm
    )

    # --------------------------------------------
    # HEADER
    # --------------------------------------------

    canvas.setFont(
        "Helvetica-Bold",
        8
    )

    canvas.setFillColor(
        NAVY
    )

    canvas.drawString(
        18 * mm,
        height - 11 * mm,
        "RESUMEIQ"
    )

    canvas.setFont(
        "Helvetica",
        7
    )

    canvas.setFillColor(
        MEDIUM_GRAY
    )

    canvas.drawRightString(
        width - 18 * mm,
        height - 11 * mm,
        "AI RECRUITMENT INTELLIGENCE"
    )

    # --------------------------------------------
    # FOOTER LINE
    # --------------------------------------------

    canvas.setStrokeColor(
        LIGHT_GRAY
    )

    canvas.setLineWidth(
        0.5
    )

    canvas.line(
        18 * mm,
        14 * mm,
        width - 18 * mm,
        14 * mm
    )

    # --------------------------------------------
    # FOOTER
    # --------------------------------------------

    canvas.setFont(
        "Helvetica",
        7
    )

    canvas.setFillColor(
        MEDIUM_GRAY
    )

    canvas.drawString(
        18 * mm,
        9 * mm,
        "Generated by ResumeIQ"
    )

    canvas.drawRightString(
        width - 18 * mm,
        9 * mm,
        f"Page {document.page}"
    )

    canvas.restoreState()


