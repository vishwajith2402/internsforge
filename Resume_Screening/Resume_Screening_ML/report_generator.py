# CREATE SCORE CARD
# ============================================================

def score_card(
    title,
    value,
    accent
):

    title_style = ParagraphStyle(
        "ScoreTitle",
        fontName="Helvetica-Bold",
        fontSize=7,
        leading=9,
        textColor=MEDIUM_GRAY,
        alignment=TA_CENTER
    )

    value_style = ParagraphStyle(
        "ScoreValue",
        fontName="Helvetica-Bold",
        fontSize=17,
        leading=20,
        textColor=accent,
        alignment=TA_CENTER
    )

    data = [[
        Paragraph(
            title.upper(),
            title_style
        )
    ], [
        Paragraph(
            format_percentage(value),
            value_style
        )]]

    table = Table(
        data,
        colWidths=[
            38 * mm
        ],
        rowHeights=[
            12 * mm,
            16 * mm
        ]
    )

    table.setStyle(
        TableStyle([
            (
                "BACKGROUND",
                (0, 0),
                (-1, -1),
                LIGHT_BG
            ),
            (
                "BOX",
                (0, 0),
                (-1, -1),
                0.7,
                LIGHT_GRAY
            ),
            (
                "VALIGN",
                (0, 0),
                (-1, -1),
                "MIDDLE"
            ),
            (
                "TOPPADDING",
                (0, 0),
                (-1, -1),
                3
            ),
            (
                "BOTTOMPADDING",
                (0, 0),
                (-1, -1),
                3
            ),
        ])
    )

    return table


# ============================================================
# LIST TO TEXT
# ============================================================

def skills_text(
    skills,
    symbol="•"
):

    if not skills:
        return "None detected"

    result = []

    for skill in skills:

        skill = str(skill).strip()

        if skill:
            result.append(
                f"{symbol} {skill}"
            )

    return "<br/>".join(
        result
    )


